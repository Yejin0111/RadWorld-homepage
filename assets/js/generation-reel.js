// Axial-only Cover Flow with default automatic cycling and manual navigation.
import { escapeHTML } from './viewer.js';

function showFrame(card, view, frame) {
  spriteFrame(card.querySelector('.gen-reel-slice'), view.sprite, frame);
  const overlay = card.querySelector('.gen-reel-mask-overlay');
  if (overlay) spriteFrame(overlay, view.overlay, frame);
}

function spriteFrame(el, sprite, frame) {
  el.style.backgroundSize = `${sprite.cols * 100}% ${sprite.rows * 100}%`;
  const x = frame % sprite.cols, y = Math.floor(frame / sprite.cols);
  el.style.backgroundPosition = `${x * 100 / Math.max(1, sprite.cols - 1)}% ${y * 100 / Math.max(1, sprite.rows - 1)}%`;
  el.dataset.frame = frame;
}

export async function initGenerationReel(root = document) {
  const reel = root.querySelector('[data-generation-reel]');
  if (!reel) return;
  let data;
  try {
    const response = await fetch('data/showcase.json');
    if (!response.ok) throw new Error('Examples unavailable');
    data = await response.json();
  } catch {
    reel.hidden = true;
    return;
  }
  const examples = ['generation', 'report', 'mask'].flatMap(kind => (data[kind] || []).map(c => ({ ...c, kind })));
  if (!examples.length) return;
  const reduced = matchMedia('(prefers-reduced-motion: reduce)');
  const category = { generation: 'Scan generation', report: 'Report-to-volume generation', mask: 'Mask-to-volume generation' };
  const inputLabel = { generation: 'Scan conditions', report: 'Radiology report', mask: 'Organ mask' };
  reel.innerHTML = `
    <div class="gen-reel-viewport" tabindex="0" role="region" aria-roledescription="carousel" aria-label="Generated CT and MRI examples, axial views">
      ${examples.map((c, i) => {
        const badge = 'Condition';
        const input = c.kind === 'report' ? `<blockquote>${escapeHTML(c.input.text)}</blockquote>`
          : c.kind === 'mask' ? ''
          : `<ul>${c.input.tags.map(t => `<li>${escapeHTML(t)}</li>`).join('')}</ul>`;
        return `<article class="gen-reel-card" data-example="${c.id}"${c.kind === 'mask' ? ' data-mask-visible="true"' : ''} role="group" aria-roledescription="slide" aria-label="${i + 1} of ${examples.length}: ${escapeHTML(c.label)}">
          <div class="gen-reel-image">
            <div class="gen-reel-slice" role="img" aria-label="Axial view of ${escapeHTML(c.label)} generated by RadWorld${c.kind === 'mask' ? ' with organ mask overlay' : ''}"></div>
            ${c.kind === 'mask' ? '<div class="gen-reel-mask-overlay" aria-hidden="true"></div>' : ''}
            <span class="gen-reel-plane">Axial</span>
            ${c.kind === 'mask' ? '<button class="gen-reel-mask-toggle" type="button" aria-label="Organ mask overlay" aria-pressed="true" title="Hide organ mask">Condition</button>' : `<details class="gen-reel-input"><summary aria-label="View ${inputLabel[c.kind].toLowerCase()}" title="${inputLabel[c.kind]}">${badge}</summary>
              <div class="gen-reel-input-panel"><p>${inputLabel[c.kind]}</p>${input}</div>
            </details>`}
          </div>
          <div class="gen-reel-caption"><h3>${escapeHTML(c.label)}</h3><p>${category[c.kind]}</p></div>
        </article>`;
      }).join('')}
    </div>
    <div class="gen-reel-controls">
      <button class="gen-reel-arrow" data-reel-step="-1" type="button" aria-label="Previous example"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="m14 6-6 6 6 6"/></svg></button>
      <div class="gen-reel-dots" role="group" aria-label="Choose an example">${examples.map((c,i) => `<button type="button" aria-label="Show ${escapeHTML(c.label)}" aria-pressed="${i === 0}" data-reel-dot="${i}"><span></span></button>`).join('')}</div>
      <button class="gen-reel-arrow" data-reel-step="1" type="button" aria-label="Next example"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="m10 6 6 6-6 6"/></svg></button>
    </div>`;

  const viewport = reel.querySelector('.gen-reel-viewport');
  const cards = [...reel.querySelectorAll('.gen-reel-card')];
  const dots = [...reel.querySelectorAll('[data-reel-dot]')];
  let selected = 0;
  let tick = 0, lastAdvance = performance.now(), dragging = null, ignoreClick = false;

  function layout() {
    const width = cards[0].offsetWidth;
    cards.forEach((card, i) => {
      let offset = (i - selected + cards.length) % cards.length;
      if (offset > cards.length / 2) offset -= cards.length;
      const distance = Math.abs(offset), side = Math.sign(offset);
      card.style.setProperty('--card-x', `${offset * width * .84}px`);
      card.style.setProperty('--card-z', `${-distance * width * .42}px`);
      card.style.setProperty('--card-angle', `${-side * Math.min(48, distance * 40)}deg`);
      card.style.zIndex = String(10 - distance);
      card.style.opacity = distance === 0 ? '1' : distance === 1 ? '.65' : distance === 2 ? '.28' : '0';
      card.dataset.position = String(offset);
      card.inert = distance > 2;
      card.setAttribute('aria-hidden', String(distance > 2));
      if (distance !== 0 && card.querySelector('details')) card.querySelector('details').open = false;
      card.classList.toggle('is-current', distance === 0);
      card.classList.toggle('is-near', distance <= 2);
      if (distance <= 2) load(i);
    });
  }
  function select(index) {
    selected = (index + cards.length) % cards.length;
    reel.dataset.selected = examples[selected].id;
    dots.forEach((dot, i) => dot.setAttribute('aria-pressed', String(i === selected)));
    layout();
  }
  function restartCycle() {
    lastAdvance = performance.now();
  }
  function go(index) {
    restartCycle();
    select(index);
  }
  dots.forEach((dot, i) => dot.addEventListener('click', () => go(i)));
  reel.querySelectorAll('[data-reel-step]').forEach(btn => btn.addEventListener('click', () => go(selected + Number(btn.dataset.reelStep))));
  viewport.addEventListener('keydown', event => {
    if (event.target.closest('summary, button')) return;
    const next = { ArrowLeft: selected - 1, ArrowRight: selected + 1, Home: 0, End: cards.length - 1 }[event.key];
    if (next === undefined) return;
    event.preventDefault();
    go(next);
  });
  viewport.addEventListener('pointerdown', event => {
    if (event.target.closest('details,button') || (event.pointerType === 'mouse' && event.button !== 0)) return;
    restartCycle();
    dragging = { id: event.pointerId, x: event.clientX, y: event.clientY, moved: false };
  });
  viewport.addEventListener('pointermove', event => {
    if (!dragging) return;
    const dx = event.clientX - dragging.x, dy = event.clientY - dragging.y;
    if (Math.abs(dx) > 8 && Math.abs(dx) > Math.abs(dy) * 1.2 && !dragging.moved) {
      dragging.moved = true;
      viewport.setPointerCapture(event.pointerId);
      viewport.classList.add('is-dragging');
    }
    if (dragging.moved) viewport.style.setProperty('--drag-shift', `${Math.max(-35, Math.min(35, dx * .2))}px`);
  });
  function finishDrag(event) {
    if (!dragging) return;
    const moved = dragging.moved, dx = event.clientX - dragging.x;
    if (viewport.hasPointerCapture(dragging.id)) viewport.releasePointerCapture(dragging.id);
    dragging = null;
    viewport.classList.remove('is-dragging');
    viewport.style.setProperty('--drag-shift', '0px');
    if (moved) {
      ignoreClick = true;
      if (Math.abs(dx) > 30 && event.type !== 'pointercancel') go(selected + (dx < 0 ? 1 : -1));
    }
  }
  viewport.addEventListener('pointerup', finishDrag);
  viewport.addEventListener('pointercancel', finishDrag);
  viewport.addEventListener('click', event => {
    if (!ignoreClick) return;
    ignoreClick = false;
    event.preventDefault();
    event.stopPropagation();
  }, true);

  function load(i) {
    const card = cards[i], view = examples[i].views.axial;
    if (card.dataset.loaded) return;
    const slice = card.querySelector('.gen-reel-slice');
    slice.style.backgroundImage = `url("${view.sprite.src}")`;
    const overlay = card.querySelector('.gen-reel-mask-overlay');
    if (overlay) overlay.style.backgroundImage = `url("${view.overlay.src}")`;
    showFrame(card, view, view.start);
    card.dataset.loaded = 'true';
  }
  cards.forEach((card, i) => {
    card.addEventListener('click', event => {
      if (!event.target.closest('details,button') && selected !== i) go(i);
    });
    const toggle = card.querySelector('.gen-reel-mask-toggle');
    if (toggle) toggle.addEventListener('click', () => {
      restartCycle();
      const on = card.dataset.maskVisible !== 'true';
      card.dataset.maskVisible = String(on);
      toggle.setAttribute('aria-pressed', String(on));
      toggle.title = on ? 'Hide organ mask' : 'Show organ mask';
      card.querySelector('.gen-reel-slice').setAttribute('aria-label', `Axial view of ${examples[i].label} generated by RadWorld${on ? ' with organ mask overlay' : ''}`);
    });
    const detail = card.querySelector('details');
    detail?.addEventListener('toggle', () => {
      if (!detail.open) return;
      restartCycle();
      cards.forEach(other => { const d = other.querySelector('details'); if (other !== card && d) d.open = false; });
    });
  });
  reduced.addEventListener('change', restartCycle);
  const timer = setInterval(() => {
    if (!reel.isConnected) { clearInterval(timer); return; }
    const rect = reel.getBoundingClientRect();
    const paused = document.hidden || rect.bottom < 0 || rect.top > innerHeight || reduced.matches || dragging || reel.querySelector('details[open]');
    reel.dataset.playback = paused ? 'paused' : 'playing';
    if (paused) { restartCycle(); return; }
    tick++;
    cards.forEach((card, i) => {
      if (Math.abs(Number(card.dataset.position)) > 1) return;
      load(i);
      const view = examples[i].views.axial;
      const cycle = 2 * (view.sprite.n - 1), offset = (tick + view.start) % cycle;
      showFrame(cards[i], view, offset < view.sprite.n ? offset : cycle - offset);
    });
    if (performance.now() - lastAdvance > 5000) go(selected + 1);
  }, 120);
  window.addEventListener('resize', layout, { passive: true });
  select(0);
  reel.classList.add('is-ready');
}
